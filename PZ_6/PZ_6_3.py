# Дан список A размера N и целое число K (1 < K < 4, K < N).
# Осуществить циклический сдвиг элементов списка вправо на K позиций
# (при этом A1 перейдет в AK+1, A2 — в AK+2, ..., AN — в AK).
# Допускается использовать вспомогательный список из 4 элементов.
import random

# ввод размера списка и числа K с проверкой
while True:
    try:
        n = int(input('Введите размер списка N (N > 2): '))
        k = int(input('Введите K (2 или 3, K < N): '))
        if n > 2 and 1 < k < 4 and k < n:
            break
        print('Нужно N > 2, K равно 2 или 3 и K < N!')
    except ValueError:
        print('Ошибка, введите целые числа!')

# заполнение списка случайными числами
a = []
i = 0
while i < n:
    a.append(random.randint(1, 100))
    i += 1
print('Исходный список:', a)

# вспомогательный список: последние K элементов
b = []
i = n - k
while i < n:
    b.append(a[i])
    i += 1

# сдвиг остальных элементов вправо на K позиций
i = n - 1
while i >= k:
    a[i] = a[i - k]
    i -= 1

# сохранённые элементы ставим в начало списка
i = 0
while i < k:
    a[i] = b[i]
    i += 1

print('Результирующий список:', a)