# Даны положительные числа A и B (A > B).
# На отрезке длины A размещено максимально возможное
# количество отрезков длины B (без наложений).
# Не используя операции умножения и деления,
# найти количество отрезков B, размещённых на отрезке A.

while True:
    try:
        A = float(input("Введите число A: "))
        B = float(input("Введите число B: "))
        assert A > B > 0
        break
    except ValueError:
        print("Ошибка! Введите корректные числа.")
    except AssertionError:
        print("Ошибка! Числа должны быть положительными, A > B.")

count = 0
length = A

while length >= B:
    length -= B
    count += 1

print("Количество отрезков:", count)
